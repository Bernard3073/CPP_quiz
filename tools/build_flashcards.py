#!/usr/bin/env python3
"""Regenerate data/flashcards.js from the Obsidian "C++ Systems Quiz.md" note.

Usage: python3 tools/build_flashcards.py [path/to/C++ Systems Quiz.md]
"""
import json
import re
import sys
from pathlib import Path

DEFAULT_SRC = Path.home() / "Documents/Obsidian Vault/cpp/C++ Systems Quiz.md"
OUT = Path(__file__).resolve().parent.parent / "data/flashcards.js"

SECTION_RE = re.compile(r"^## ([A-Z])\. (.+?)\s*(?:\(\d+\))?\s*(?:—.*)?$")
QUESTION_RE = re.compile(r"^\*\*([A-Z]\d+)\.\*\*\s*(.+)$")


def parse(text):
    # Only the English half of the bilingual note.
    text = text.split('<div class="lang-zh">')[0]
    cards, section, current = [], None, None
    for line in text.splitlines():
        m = SECTION_RE.match(line)
        if m:
            section = m.group(2).strip()
            continue
        m = QUESTION_RE.match(line)
        if m:
            current = {"id": m.group(1), "section": section, "q": m.group(2).strip(), "a": []}
            cards.append(current)
            continue
        if current is None:
            continue
        if line.startswith("> [!answer]"):
            continue
        if line.startswith(">"):
            current["a"].append(line[2:] if line.startswith("> ") else line[1:])
        elif line.strip() == "" and current["a"]:
            current = None
    for c in cards:
        c["a"] = "\n".join(c["a"]).strip()
    return cards


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SRC
    cards = parse(src.read_text(encoding="utf-8"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by tools/build_flashcards.py from \"C++ Systems Quiz.md\" — do not edit by hand.\n"
        "window.FLASHCARDS = " + json.dumps(cards, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(cards)} cards to {OUT}")


if __name__ == "__main__":
    main()
